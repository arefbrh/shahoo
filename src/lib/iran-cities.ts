export function getCitiesForProvince(provinceName: string): string[] {
  if (!provinceName) return [];
  const key = provinceName.trim() as (typeof IRAN_PROVINCES)[number];
  return IRAN_CITIES_BY_PROVINCE[key] || [];
}

export { IRAN_PROVINCES };

export function isValidCityForProvince(provinceName: string, cityName: string): boolean {
  const cities = getCitiesForProvince(provinceName);
  return cities.includes(cityName.trim());
}
